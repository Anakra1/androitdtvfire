"""Remove only explicitly named CBR components, preserving settings by default."""
import os
import shutil
from pathlib import Path
import xml.etree.ElementTree as ET

IDS = ('skin.crimsonbloodrequiem','plugin.video.stremio.bridge',
       'script.module.cbr.engine','repository.crb.android','repository.crb.windows',
       'script.crb.wizard')


def targets(addons):
    root=Path(addons).resolve()
    result=[]
    for identity in IDS:
        path=root/identity
        if not path.exists():continue
        if path.is_symlink() or path.resolve().parent!=root:
            raise ValueError('A CBR component points outside Kodi addons. Nothing was removed.')
        manifest=ET.parse(path/'addon.xml').getroot()
        if manifest.get('id')!=identity:
            raise ValueError('A CBR component has an unexpected identity. Nothing was removed.')
        result.append((identity,path))
    return result


def blockers(installed):
    return [a.get('name',a['addonid']) for a in installed if a['addonid'] not in IDS
            and any(d.get('addonid') in IDS and not d.get('optional',False)
                    for d in a.get('dependencies',[]))]


def disable_tv(profile):
    """Keep every TV instance; disable only paths generated by CBR."""
    for path in Path(profile).glob('instance-settings-*.xml'):
        tree=ET.parse(path);root=tree.getroot();values={s.get('id'):s.text for s in root.findall('setting')}
        address=(values.get('m3uPath')or'').replace('\\','/')
        if not address.endswith('/addon_data/plugin.video.stremio.bridge/pvr/channels.m3u'):continue
        node=next((s for s in root.findall('setting')if s.get('id')=='kodi_addon_instance_enabled'),None)
        if node is not None:node.text='false'
        tree.write(path,encoding='utf-8',xml_declaration=True)


def remove_files(addons, userdata, remove_settings=False):
    plan=targets(addons)  # Validate the entire plan before removing anything.
    data_root=Path(userdata).resolve()
    settings=[]
    if remove_settings:
        for identity in IDS:
            path=data_root/identity
            if path.exists():
                if path.is_symlink() or path.resolve().parent!=data_root:
                    raise ValueError('A settings folder points outside Kodi userdata. Nothing was removed.')
                settings.append(path)
    for identity,path in plan:shutil.rmtree(path)
    for path in settings:shutil.rmtree(path)
    return [i for i,p in plan]


def run(rpc):
    import xbmc
    import xbmcgui
    import xbmcvfs
    dialog=xbmcgui.Dialog()
    if rpc('Settings.GetSettingValue',{'setting':'lookandfeel.skin'})['value']=='skin.crimsonbloodrequiem':
        dialog.ok('Remove CBR','First select Settings → Interface → Skin → Estuary and confirm “Keep skin”. Then run CBR Setup Wizard → Uninstall CBR again. Your settings will stay in place.')
        rpc('GUI.ActivateWindow',{'window':'settingsinterface'})
        return
    if rpc('Player.GetActivePlayers',{}):
        dialog.ok('Remove CBR','Stop playback before removing CBR.');return
    installed=rpc('Addons.GetAddons',{'properties':['name','dependencies']})['addons']
    needed=blockers(installed)
    if needed:
        dialog.ok('CBR is still needed','These other addons depend on CBR: '+', '.join(needed)+'. Remove those dependencies yourself before trying again. Nothing was removed.');return
    addons=xbmcvfs.translatePath('special://home/addons/')
    userdata=xbmcvfs.translatePath('special://profile/addon_data/')
    plan=targets(addons)
    if not dialog.yesno('Uninstall CBR','Remove the CBR video addon, skin, engine, wizard and CBR repositories listed below? Kodi and your other addons stay installed.\n\n'+', '.join(i for i,p in plan)):
        return
    erase=dialog.yesno('Remove CBR settings too?','Choose No to keep your manifests, favourites and channel settings for a reinstall. Choose Yes only for a fresh start.',yeslabel='Remove settings',nolabel='Keep settings')
    for identity,path in plan:
        if identity == 'script.crb.wizard':continue
        try:rpc('Addons.SetAddonEnabled',{'addonid':identity,'enabled':False})
        except Exception:pass
    xbmc.Monitor().waitForAbort(3)
    disable_tv(os.path.join(userdata,'pvr.iptvsimple'))
    remove_files(addons,userdata,erase)
    # Kodi rescans its own registry. No native database is edited directly.
    xbmc.executebuiltin('UpdateLocalAddons')
    dialog.ok('CBR removed','Fully close and reopen Kodi to finish. Your other addons and TV configurations were kept. '+('CBR settings were removed.' if erase else 'CBR settings were kept for a reinstall.'))
