"""Opt-in integration check against an Android engine forwarded to port 18767.

Uses generated bytes and a local BitTorrent seed; no external media or trackers.
Run with CBR_ANDROID_TEST=1 and CBR_TEST_SEED pointing to cbr-test-seed.exe.
"""
import hashlib
from contextlib import suppress
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
import os
from pathlib import Path
import socket
import struct
import subprocess
import sys
import tempfile
import threading
import time
import unittest
from urllib.parse import urlencode
from urllib.request import Request, urlopen

sys.path.insert(0, str(Path(__file__).parent / 'plugin.video.stremio.bridge'))
from engine import Client, prepare_torrent


def bencode(value):
    if isinstance(value, bytes):
        return str(len(value)).encode() + b':' + value
    if isinstance(value, int):
        return b'i' + str(value).encode() + b'e'
    if isinstance(value, dict):
        return b'd' + b''.join(bencode(k) + bencode(value[k]) for k in sorted(value)) + b'e'
    raise TypeError(type(value))


@unittest.skipUnless(os.environ.get('CBR_ANDROID_TEST') == '1', 'Requires the isolated Android test engine')
class AndroidBufferingTest(unittest.TestCase):
    def test_torrent_metadata_buffering_and_byte_exact_range_seeking(self):
        data = bytes(range(256)) * 8192
        piece_size = 65536
        info = {b'name': b'cbr-test.mp4', b'length': len(data), b'piece length': piece_size,
                b'pieces': b''.join(hashlib.sha1(data[p:p + piece_size]).digest()
                                   for p in range(0, len(data), piece_size))}
        torrent_hash = hashlib.sha1(bencode(info)).hexdigest()
        tracker = 'http://10.0.2.2:18900/announce'
        metadata = bencode({b'info': info, b'announce': tracker.encode()})

        class Tracker(BaseHTTPRequestHandler):
            calls = 0

            def do_GET(self):
                Tracker.calls += 1
                response = bencode({b'interval': 5, b'complete': 1, b'incomplete': 0,
                                    b'peers': socket.inet_aton('10.0.2.2') + struct.pack('!H', 18901)})
                self.send_response(200)
                self.send_header('Content-Length', str(len(response)))
                self.end_headers()
                self.wfile.write(response)

            def log_message(self, *args):
                pass

        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            (root / 'cbr-test.mp4').write_bytes(data)
            (root / 'test.torrent').write_bytes(metadata)
            seed_log = (root / 'seed.log').open('wb')
            seed = subprocess.Popen([os.environ['CBR_TEST_SEED'], str(root / 'test.torrent')],
                                    stdout=seed_log, stderr=subprocess.STDOUT,
                                    creationflags=getattr(subprocess, 'CREATE_NO_WINDOW', 0))
            server = ThreadingHTTPServer(('127.0.0.1', 18900), Tracker)
            thread = threading.Thread(target=server.serve_forever, daemon=True)
            thread.start()
            client = Client('http://127.0.0.1:18767')
            try:
                self.assertTrue(client.alive())
                settings = client.call('/settings', {'action': 'get'})
                settings.update({'CacheSize': 64 * 1024 * 1024, 'PreloadCache': 10,
                                 'UseDisk': False, 'DisableUpload': True, 'DisableUPNP': True,
                                 'EnableDLNA': False, 'EnableBonjour': False, 'EnableLPD': False,
                                 'RetrackersMode': 0, 'DefaultTrackers': '', 'DisableDHT': True, 'DisablePEX': True})
                client.call('/settings', {'action': 'set', 'sets': settings})
                time.sleep(1)
                if seed.poll() is not None:
                    raise RuntimeError((root / 'seed.log').read_text(errors='replace'))
                magnet = 'magnet:?' + urlencode({'xt': 'urn:btih:' + torrent_hash, 'tr': tracker})
                try:
                    url, actual_hash = prepare_torrent(client, magnet, 0, timeout=45)
                except Exception:
                    print('Local tracker requests:', Tracker.calls)
                    print('Seed output:', (root / 'seed.log').read_text(errors='replace'))
                    raise
                self.assertEqual(actual_hash, torrent_hash)
                self.assertGreater(Tracker.calls, 0)
                for start in (0, 1500000):
                    end = start + 65535
                    request = Request(url, headers={'Range': 'bytes={}-{}'.format(start, end)})
                    with urlopen(request, timeout=15) as response:
                        self.assertEqual(response.status, 206)
                        self.assertEqual(response.read(), data[start:end + 1])
                print('Android shared engine: local peer metadata, buffering and two exact range reads passed.')
            finally:
                with suppress(Exception):
                    client.remove(torrent_hash)
                server.shutdown()
                server.server_close()
                seed.terminate()
                seed.wait(timeout=10)
                seed_log.close()


if __name__ == '__main__':
    unittest.main(verbosity=2)
