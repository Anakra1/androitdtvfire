"""Windows engine and localhost client with an Android companion handoff."""
import hashlib
import json
import os
import platform
import socket
import subprocess
import sys
import time
from urllib.parse import quote, urlencode
from urllib.request import ProxyHandler, Request, build_opener

ENGINE_SHA256 = '3a96b97a24d86a90c0712a6ec47d4ed52edc7eabac1bce6a0d9bbc8fd30de5bb'
ANDROID_COMPANION_PACKAGE = 'com.crimsonbloodrequiem.companion'
ANDROID_COMPANION_PORT = 8766
OPENER = build_opener(ProxyHandler({}))  # Local playback must not use an HTTP proxy.


def _sha256(path):
    digest = hashlib.sha256()
    with open(path, 'rb') as source:
        for block in iter(lambda: source.read(1024 * 1024), b''):
            digest.update(block)
    return digest.hexdigest()


def _android_arch():
    try:
        import xbmc
        if not xbmc.getCondVisibility('System.Platform.Android'):
            return None
    except Exception:
        if sys.platform != 'android' and not os.environ.get('ANDROID_ROOT'):
            return None
    machine = platform.machine().lower()
    if machine in ('aarch64', 'arm64'):
        return 'arm64'
    if machine in ('armv7l', 'armv7', 'arm'):
        return 'arm7'
    if machine in ('x86_64', 'amd64'):
        return 'amd64'
    if machine in ('i386', 'i486', 'i586', 'i686', 'x86'):
        return '386'
    raise RuntimeError('This Android device architecture ({}) is not supported.'.format(machine or 'unknown'))


def write_json(path, value):
    import tempfile
    os.makedirs(os.path.dirname(path), exist_ok=True)
    fd, temporary = tempfile.mkstemp(dir=os.path.dirname(path), suffix='.tmp')
    try:
        with os.fdopen(fd, 'w', encoding='utf-8') as output:
            json.dump(value, output)
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def read_json(path):
    try:
        with open(path, encoding='utf-8') as source:
            return json.load(source)
    except (OSError, ValueError):
        return {}


class Client:
    def __init__(self, endpoint):
        # Endpoints are generated by our service, never by a remote provider.
        from urllib.parse import urlsplit
        parts = urlsplit(endpoint)
        if parts.scheme != 'http' or parts.hostname != '127.0.0.1' or not parts.port or parts.path:
            raise ValueError('Invalid local engine endpoint.')
        self.endpoint = endpoint

    def call(self, route, data=None, timeout=5):
        payload = json.dumps(data).encode('utf-8') if data is not None else None
        req = Request(self.endpoint + route, data=payload, headers={'Content-Type': 'application/json'})
        with OPENER.open(req, timeout=timeout) as response:
            raw = response.read(4 * 1024 * 1024)
        return json.loads(raw) if raw else {}

    def alive(self):
        try:
            with OPENER.open(self.endpoint + '/echo', timeout=1) as response:
                return response.read(100).decode().startswith('MatriX.')
        except Exception:
            return False

    def status(self, torrent_hash):
        return self.call('/torrents', {'action': 'get', 'hash': torrent_hash})

    def remove(self, torrent_hash):
        return self.call('/torrents', {'action': 'rem', 'hash': torrent_hash})

    def stream_url(self, torrent_hash, file_id, name='video', preload=False):
        params = {'link': torrent_hash, 'index': file_id}
        params['preload' if preload else 'play'] = 'true'
        if preload:
            params['stat'] = 'true'
        return self.endpoint + '/stream/' + quote(name.rsplit('/', 1)[-1], safe='') + '?' + urlencode(params)


class FileSelectionRequired(ValueError):
    pass


def select_file(files, original_index=None, filename=None):
    if original_index is not None:
        if isinstance(original_index, bool) or not isinstance(original_index, int) or original_index < 0:
            raise ValueError('Invalid torrent file index.')
        # TorrServer sorts files naturally, so its IDs do NOT map to Stremio's
        # original torrent order. Never silently play the wrong episode.
    if len(files) == 1:
        return files[0]
    if filename:
        match = [f for f in files if f.get('path', '').rsplit('/', 1)[-1] == filename.rsplit('/', 1)[-1]]
        if len(match) == 1:
            return match[0]
    if original_index is not None:
        raise FileSelectionRequired('Choose the video file in this torrent pack.')
    video_extensions = ('.mkv', '.mp4', '.avi', '.webm', '.mov', '.m4v', '.ts')
    candidates = [f for f in files if f.get('path', '').lower().endswith(video_extensions)]
    if not candidates:
        raise ValueError('No supported video file was found in this torrent.')
    return max(candidates, key=lambda f: f.get('length', 0))


class Engine:
    def __init__(self, addon_path, data_path, cache_mb=128):
        self.addon_path, self.data_path = addon_path, data_path
        self.cache_mb = max(64, min(512, int(cache_mb)))
        self.process = None
        self.client = None
        self.diagnostic_path = None  # Development tests only; no production log files.
        self.console = None

    def start(self, progress=None):
        if os.name == 'nt':
            binary = os.path.join(self.addon_path, 'resources', 'bin', 'windows-x64', 'TorrServer.exe')
            if _sha256(binary) != ENGINE_SHA256:
                raise RuntimeError('The bundled torrent engine failed its integrity check.')
        else:
            arch = _android_arch()
            if not arch:
                raise RuntimeError('The built-in torrent player supports Windows and Android devices.')
            self.client = Client('http://127.0.0.1:{}'.format(ANDROID_COMPANION_PORT))
            if not self.client.alive():
                deadline = time.monotonic() + 90
                while not self.client.alive():
                    if progress:
                        progress(0, 'Connecting to CBR torrent player…')
                    if time.monotonic() > deadline:
                        raise RuntimeError(
                            'Fire TV did not start the CBR torrent player. Android blocked the launch; '
                            'check that CBR Kodi Companion is installed and enabled.')
                    time.sleep(0.25)
        os.makedirs(self.data_path, exist_ok=True)
        if os.name == 'nt':
            with socket.socket() as listener:
                listener.bind(('127.0.0.1', 0))
                port = listener.getsockname()[1]
            self.client = Client('http://127.0.0.1:{}'.format(port))
            args = [binary, '--ip', '127.0.0.1', '--port', str(port), '--path', self.data_path,
                    '--logpath', self.diagnostic_path or os.devnull, '--weblogpath', os.devnull]
            if self.diagnostic_path:
                self.console = open(self.diagnostic_path + '.console', 'wb')
            process_options = {'cwd': self.data_path, 'stdin': subprocess.DEVNULL,
                               'stdout': self.console or subprocess.DEVNULL,
                               'stderr': self.console or subprocess.DEVNULL,
                               'creationflags': subprocess.CREATE_NO_WINDOW}
            try:
                self.process = subprocess.Popen(args, **process_options)
            except OSError:
                raise
            deadline = time.monotonic() + 15
            while not self.client.alive():
                if self.process.poll() is not None or time.monotonic() > deadline:
                    self.stop()
                    raise RuntimeError('The torrent engine could not start.')
                time.sleep(0.1)

        settings = self.client.call('/settings', {'action': 'get'})
        settings.update({'CacheSize': self.cache_mb * 1024 * 1024, 'PreloadCache': 10,
                         'ReaderReadAHead': 95, 'UseDisk': False, 'DisableUpload': True,
                         'DisableUPNP': True, 'EnableDLNA': False, 'EnableBonjour': False,
                         'EnableLPD': False, 'EnableRutorSearch': False, 'EnableTorznabSearch': False,
                         'TorrentDisconnectTimeout': 60, 'RemoveCacheOnDrop': True, 'RetrackersMode': 0})
        self.client.call('/settings', {'action': 'set', 'sets': settings}, timeout=30)
        return self.client

    def stop(self):
        if os.name != 'nt':
            try:
                import xbmc
                xbmc.executebuiltin(
                    'StartAndroidActivity({},android.intent.action.VIEW,,cbr://stop)'.format(
                        ANDROID_COMPANION_PACKAGE))
            except Exception:
                pass
            self.client = None
            return
        if self.process and self.process.poll() is None:
            self.process.terminate()
            try:
                self.process.wait(timeout=5)
            except subprocess.TimeoutExpired:
                self.process.kill()
                self.process.wait(timeout=5)
        self.process = None
        if self.console:
            self.console.close()
            self.console = None


def prepare_torrent(client, link, original_index=None, progress=None, cancelled=None, timeout=120, filename=None, file_selector=None):
    """Resolve metadata, prebuffer the file, and return a seekable local URL."""
    import threading
    progress = progress or (lambda percent, message: None)
    cancelled = cancelled or (lambda: False)
    deadline = time.monotonic() + timeout
    info = client.call('/torrents', {'action': 'add', 'link': link, 'save_to_db': False})
    torrent_hash = info.get('hash')
    if not torrent_hash:
        raise RuntimeError('The torrent engine did not return a torrent ID.')
    try:
        while not info.get('file_stats'):
            if cancelled():
                raise InterruptedError('Torrent loading cancelled.')
            if time.monotonic() > deadline:
                raise RuntimeError('No torrent metadata arrived. Try a source with more peers.')
            progress(0, 'Finding peers and loading torrent metadata…')
            time.sleep(0.25)
            info = client.status(torrent_hash)
        try:
            selected = select_file(info['file_stats'], original_index, filename)
        except FileSelectionRequired:
            if not file_selector:
                raise
            selected = file_selector(info['file_stats'])
            if selected is None:
                raise InterruptedError('Torrent file selection cancelled.')
        result, done = {}, threading.Event()

        def preload():
            try:
                route = client.stream_url(torrent_hash, selected['id'], selected['path'], preload=True)[len(client.endpoint):]
                client.call(route, timeout=timeout)
            except Exception as error:
                result['error'] = error
            finally:
                done.set()

        worker = threading.Thread(target=preload, daemon=True)
        worker.start()
        while not done.wait(0.25):
            if cancelled():
                raise InterruptedError('Torrent buffering cancelled.')
            if time.monotonic() > deadline:
                raise RuntimeError('Buffering timed out. Try a source with more peers.')
            info = client.status(torrent_hash)
            target, received = info.get('preload_size', 0), info.get('preloaded_bytes', 0)
            percent = min(99, int(100 * received / target)) if target else 0
            progress(percent, 'Buffering: {:.1f} MB / {:.1f} MB · {} peers · {:.1f} MB/s'.format(
                received / 1048576, target / 1048576, info.get('active_peers', 0), info.get('download_speed', 0) / 1048576))
        if cancelled():
            raise InterruptedError('Torrent buffering cancelled.')
        if result.get('error'):
            raise RuntimeError('The torrent could not be buffered. Try another source.') from result['error']
        progress(100, 'Starting playback…')
        return client.stream_url(torrent_hash, selected['id'], selected['path']), torrent_hash
    except Exception:
        try:
            client.remove(torrent_hash)
        except Exception:
            pass
        raise
